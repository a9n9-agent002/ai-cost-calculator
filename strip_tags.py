import re, html, sys
p = sys.argv[1] if len(sys.argv) > 1 else "/opt/data/workspace/costcalc/site/index.html"
t = open(p, encoding="utf-8").read()
t = re.sub(r"<style.*?</style>", "", t, flags=re.S)
t = re.sub(r"<tr>", "\n| ", t)
t = re.sub(r"<t[dh][^>]*>", " | ", t)
t = re.sub(r"<h2[^>]*>", "\n\n## ", t)
t = re.sub(r"<h1[^>]*>", "\n# ", t)
t = re.sub(r"<h3[^>]*>", "\n### ", t)
t = re.sub(r"<p[^>]*>", "\n", t)
t = re.sub(r"<li[^>]*>", "\n- ", t)
t = re.sub(r"<[^>]+>", "", t)
t = html.unescape(t)
t = re.sub(r"[ \t]+", " ", t)
t = re.sub(r"\n\s*\n+", "\n", t)
print(t.strip())
